export const currencyRates: Record<string, { symbol: string; rate: number; name: string }> = {
  USD: { symbol: "$", rate: 1.0, name: "US Dollar" },
  EUR: { symbol: "€", rate: 0.92, name: "Euro" },
  GBP: { symbol: "£", rate: 0.78, name: "British Pound" },
  JPY: { symbol: "¥", rate: 154.5, name: "Japanese Yen" },
  CAD: { symbol: "CA$", rate: 1.36, name: "Canadian Dollar" },
  AUD: { symbol: "AU$", rate: 1.52, name: "Australian Dollar" },
  CHF: { symbol: "CHF", rate: 0.89, name: "Swiss Franc" },
  AED: { symbol: "AED", rate: 3.67, name: "UAE Dirham" }
};

export function formatCurrency(amount: number, currencyCode = 'USD'): string {
  const meta = currencyRates[currencyCode] || currencyRates.USD;
  const converted = amount * meta.rate;
  if (currencyCode === 'JPY') {
    return `${meta.symbol}${Math.round(converted).toLocaleString()}`;
  }
  return `${meta.symbol}${converted.toLocaleString(undefined, { minimumFractionDigits: 2, maximumFractionDigits: 2 })}`;
}
